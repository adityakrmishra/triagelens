import pytest
from shopflow.checkout import resolve_free_shipping


def test_reproduce_free_shipping_boundary_condition():
    """
    Customer complaint:
      Customer ordered goods totaling exactly ₹1,000 (qualifying threshold).
      Checkout charged ₹99 standard shipping fee.

    Expected behavior:
      Orders >= ₹1,000 threshold should receive free shipping (shipping fee = 0.0).
    """
    cart_subtotal = 1000.0
    cart_after_discount = 1000.0
    threshold = 1000.0

    actual = resolve_free_shipping(
        cart_subtotal=cart_subtotal,
        cart_after_discount=cart_after_discount,
        threshold=threshold,
    )

    expected = 0.0
    assert actual == expected, (
        f"Silent bug reproduced: Boundary order of exact {threshold} charged shipping "
        f"(expected {expected}, got {actual})"
    )
