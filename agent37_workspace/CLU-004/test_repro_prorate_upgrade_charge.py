import pytest
from shopflow.subscriptions import prorate_upgrade_charge


def test_reproduce_subscription_upgrade_inverted_proration():
    """
    Customer complaint:
      Upgraded plan mid-cycle with 5 days remaining in 30-day month.
      Overcharged for 25 consumed days instead of 5 remaining days.

    Expected behavior:
      Charge should only be for remaining 5 days:
      (1000 - 500) / 30 * 5 = ₹83.33.
    """
    current_plan_price = 500.0
    new_plan_price = 1000.0
    days_remaining = 5
    billing_cycle_days = 30

    actual = prorate_upgrade_charge(
        current_plan_price=current_plan_price,
        new_plan_price=new_plan_price,
        days_remaining=days_remaining,
        billing_cycle_days=billing_cycle_days,
    )

    expected = 83.33
    assert abs(actual - expected) <= 0.05, (
        f"Silent bug reproduced: Proration charged for 25 used days instead of 5 remaining days "
        f"(expected {expected}, got {actual})"
    )
