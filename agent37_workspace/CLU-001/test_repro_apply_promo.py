import pytest
from shopflow.pricing import apply_promo


def test_reproduce_vip25_silent_failure_on_sale_item():
    """
    Customer complaint:
      VIP customer entered VIP25 at checkout with a clearance/sale item in cart.
      UI indicated code was applied, but order total remained unchanged (₹2,000).

    Expected behavior:
      VIP25 should reduce the ₹2,000 cart total by 25% -> ₹1,500.00.
    """
    cart_total = 2000.0
    promo_code = "VIP25"
    has_sale_item = True
    is_vip = True

    actual = apply_promo(
        cart_total=cart_total,
        promo_code=promo_code,
        has_sale_item=has_sale_item,
        is_vip=is_vip,
    )

    expected = 1500.0
    assert actual == expected, (
        f"Silent bug reproduced: VIP25 promo ignored when has_sale_item=True "
        f"(expected {expected}, got {actual})"
    )
