import pytest
from shopflow.auth_session import check_magic_link_expiry


def test_reproduce_magic_link_premature_expiry():
    """
    Customer complaint:
      User received magic link email and clicked within 30 seconds.
      Link reported as 'Expired' instead of remaining valid for 15 minutes.

    Expected behavior:
      Link should remain valid (return True) 30 seconds after issuance when TTL is 15 minutes.
    """
    issued_at_epoch = 1700000000
    current_epoch = 1700000030  # 30 seconds elapsed
    ttl_minutes = 15

    actual = check_magic_link_expiry(
        issued_at_epoch=issued_at_epoch,
        current_epoch=current_epoch,
        ttl_minutes=ttl_minutes,
    )

    assert actual is True, (
        f"Silent bug reproduced: Magic link expired after 30 seconds instead of 15 minutes "
        f"(expected True, got {actual})"
    )
