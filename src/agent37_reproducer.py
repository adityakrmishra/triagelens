def _is_placeholder(key: str) -> bool:
    """True if key is missing, empty, or a dummy placeholder."""
    if not key or not key.strip():
        return True
    lower = key.strip().lower()
    return lower.startswith("your_") or lower in ("none", "null", "placeholder", "test")


