# ---------------------------------------------------------------------------
# Agent37 Sandbox Runner
# ---------------------------------------------------------------------------

def reproduce_bug_in_agent37(
    cluster: dict,
    top_function: dict,
    repo_path: str = "demo_target_repo",
) -> dict[str, Any]:
    """
    Execute isolated bug reproduction inside the Agent37 sandbox runner.

    1. Generates test code and writes it to `agent37_workspace/<cluster_id>/`.
    2. Writes sandbox execution manifest `sandbox_manifest.json`.
    3. Runs pytest in an isolated subprocess with target repo on PYTHONPATH.
    4. Verifies silent bug confirmation (exit code 1 with AssertionError).

    Args:
        cluster:      Normalized ticket cluster dict.
        top_function: Rank #1 suspect function metadata from ChromaDB.
        repo_path:    Relative or absolute path to the target repository.

    Returns:
        dict containing sandbox status, bug reproduction boolean, failure trace,
        and execution duration.
    """
    cluster_id = cluster.get("cluster_id", "CLU-001")
    fn_name = top_function.get("function_name", "unknown")
    start_time = time.perf_counter()

    # 1. Prepare workspace directory
    workspace_dir = Path("agent37_workspace") / cluster_id
    workspace_dir.mkdir(parents=True, exist_ok=True)

    # 2. Generate and write test file
    test_code = generate_repro_test_code(cluster, top_function)
    test_file_path = workspace_dir / f"test_repro_{fn_name}.py"
    test_file_path.write_text(test_code, encoding="utf-8", errors="replace")

    # 3. Create sandbox manifest
    instance_id = AGENT37_INSTANCE_ID
    manifest = {
        "agent37_instance_id": instance_id,
        "cluster_id": cluster_id,
        "target_function": top_function.get("function_id", fn_name),
        "target_file": top_function.get("file_path", ""),
        "timestamp": datetime.now(timezone.utc).isoformat(),
        "status": "DISPATCHED",
    }
    manifest_path = workspace_dir / "sandbox_manifest.json"
    manifest_path.write_text(json.dumps(manifest, indent=2), encoding="utf-8", errors="replace")

    # Optional Agent37 API handshake if key is present
    if not _is_placeholder(AGENT37_API_KEY):
        try:
            import requests

            dispatch_url = f"{AGENT37_BASE_URL}/instances/{instance_id}/execute"
            payload = {
                "instance_id": instance_id,
                "command": f"pytest {test_file_path.as_posix()}",
                "workspace": cluster_id,
            }
            requests.post(
                dispatch_url,
                json=payload,
                headers={"Authorization": f"Bearer {AGENT37_API_KEY.strip()}"},
                timeout=5,
            )
        except Exception:
            pass  # Fallback to local isolated subprocess runner

    # 4. Execute test via pytest in isolated subprocess
    abs_repo = Path(repo_path).resolve()
    env = dict(os.environ)
    existing_pythonpath = env.get("PYTHONPATH", "")
    env["PYTHONPATH"] = (
        f"{abs_repo};{existing_pythonpath}" if existing_pythonpath else str(abs_repo)
    )

    cmd = [
        sys.executable,
        "-m",
        "pytest",
        str(test_file_path),
        "-v",
        "--tb=short",
    ]

    try:
        proc = subprocess.run(
            cmd,
            capture_output=True,
            text=True,
            encoding="utf-8",
            errors="replace",
            env=env,
            timeout=15,
        )
        stdout = proc.stdout + "\n" + proc.stderr
        returncode = proc.returncode
    except subprocess.TimeoutExpired:
        stdout = "Agent37 sandbox test execution timed out (15s)."
        returncode = -1
    except Exception as exc:
        stdout = f"Agent37 sandbox execution error: {exc}"
        returncode = -1

    elapsed_ms = int((time.perf_counter() - start_time) * 1000)

    # 5. Analyze results: Silent bug is confirmed when test FAILS via AssertionError
    bug_reproduced = False
    failure_summary = ""

    if returncode == 1 and ("AssertionError" in stdout or "FAILED" in stdout):
        bug_reproduced = True
        sandbox_status = "CONFIRMED_SILENT_BUG"

        # Extract concise failure reason
        for line in stdout.splitlines():
            line_s = line.strip()
            if line_s.startswith("E   AssertionError:") or line_s.startswith("E       AssertionError:"):
                failure_summary = line_s.split("AssertionError:", 1)[1].strip()
                break
            elif "Silent bug reproduced:" in line_s:
                idx = line_s.find("Silent bug reproduced:")
                failure_summary = line_s[idx:].strip()
                break

        if not failure_summary:
            failure_summary = f"Assertion failed in {fn_name}() under customer test parameters."

    elif returncode == 0:
        bug_reproduced = False
        sandbox_status = "PASSED"
        failure_summary = "Test passed; unable to trigger assertion failure."
    else:
        bug_reproduced = False
        sandbox_status = "ERROR"
        failure_summary = f"Test execution crashed with exit code {returncode}."

    # Update manifest
    manifest["status"] = sandbox_status
    manifest["bug_reproduced"] = bug_reproduced
    manifest["duration_ms"] = elapsed_ms
    manifest_path.write_text(json.dumps(manifest, indent=2), encoding="utf-8", errors="replace")

    return {
        "cluster_id": cluster_id,
        "function_name": fn_name,
        "agent37_instance_id": instance_id,
        "sandbox_status": sandbox_status,
        "bug_reproduced": bug_reproduced,
        "test_file_path": test_file_path.as_posix(),
        "test_code": test_code,
        "pytest_stdout": stdout,
        "failure_summary": failure_summary,
        "duration_ms": elapsed_ms,
    }
